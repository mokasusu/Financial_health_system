    def _extract_data_quality_warnings(
        self, ratio_report: FinancialRatioReport
    ) -> List[FinancialWarning]:
        """Scan ratio report warnings for mapping needs_review flags."""
        warnings: List[FinancialWarning] = []
        needs_review_items: List[str] = []

        for r in ratio_report.ratios.values():
            for w in r.warnings:
                if "needs_review" in w:
                    needs_review_items.append(r.name)
                    break

        if needs_review_items:
            unique_items = sorted(list(set(needs_review_items)))
            warnings.append(
                FinancialWarning(
                    code="DATA_QUALITY_NEEDS_REVIEW",
                    category=WarningCategory.DATA_QUALITY,
                    severity=WarningSeverity.MEDIUM,
                    title=f"Có {len(unique_items)} chỉ số sử dụng dữ liệu cần rà soát (needs_review)",
                    message=(
                        f"Các chỉ số sau được tính toán dựa trên khoản mục có độ tin cậy mapping chưa tối đa: "
                        f"{', '.join(unique_items)}. Cần kiểm tra đối chiếu lại với bản scan gốc."
                    ),
                    related_ratios=list(set(r for r, item in ratio_report.ratios.items() if item.name in unique_items)),
                    evidence="Khoản mục có trạng thái MappingStatus.NEEDS_REVIEW",
                    recommendation="Kiểm tra lại bước ánh xạ ngữ nghĩa hoặc can thiệp thủ công xác nhận khoản mục.",
                )
            )

        return warnings

    def _prioritize_and_deduplicate_warnings(
        self, warnings: List[FinancialWarning]
    ) -> List[FinancialWarning]:
        """Deduplicate warnings by code and sort by severity (CRITICAL > HIGH > MEDIUM > LOW > INFO)."""
        severity_order = {
            WarningSeverity.CRITICAL: 0,
            WarningSeverity.HIGH: 1,
            WarningSeverity.MEDIUM: 2,
            WarningSeverity.LOW: 3,
            WarningSeverity.INFO: 4,
        }

        seen_codes = set()
        deduped: List[FinancialWarning] = []

        for w in warnings:
            if w.code not in seen_codes:
                seen_codes.add(w.code)
                deduped.append(w)

        deduped.sort(key=lambda x: severity_order.get(x.severity, 99))
        return deduped

    def _determine_overall_status(
        self,
        assessments: Dict[str, RatioAssessment],
        warnings: List[FinancialWarning],
    ) -> OverallHealthStatus:
        """Synthesize overall financial health status based on transparent rules."""
        # Condition 1: Significant missing data
        missing_count = sum(1 for a in assessments.values() if a.status == AssessmentStatus.NOT_AVAILABLE)
        if missing_count >= 4:
            return OverallHealthStatus.INSUFFICIENT_DATA

        # Check if entire key category is missing
        liq_missing = all(assessments[k].status == AssessmentStatus.NOT_AVAILABLE for k in ["current_ratio", "quick_ratio", "cash_ratio"] if k in assessments)
        if liq_missing:
            return OverallHealthStatus.INSUFFICIENT_DATA

        # Condition 2: Critical or High Alerts present
        has_critical = any(w.severity == WarningSeverity.CRITICAL for w in warnings)
        has_high = any(w.severity == WarningSeverity.HIGH for w in warnings)
        alert_count = sum(1 for a in assessments.values() if a.status in (AssessmentStatus.ALERT, AssessmentStatus.UNDEFINED))

        if has_critical or has_high or alert_count >= 1:
            return OverallHealthStatus.NEEDS_ATTENTION

        # Condition 3: Mixed / Watch items
        watch_count = sum(1 for a in assessments.values() if a.status == AssessmentStatus.WATCH)
        has_medium = any(w.severity == WarningSeverity.MEDIUM for w in warnings)

        if watch_count >= 1 or has_medium:
            return OverallHealthStatus.MIXED

        # Condition 4: No major rule-based alerts triggered
        return OverallHealthStatus.NO_MAJOR_RULE_BASED_ALERTS

    def _build_category_overviews(
        self, assessments: Dict[str, RatioAssessment]
    ) -> Dict[str, str]:
        """Generate synthesized narrative overviews for each of the 4 analytical groups."""
        overviews: Dict[str, str] = {}

        # 1. Thanh khoản
        cr = assessments.get("current_ratio")
        qr = assessments.get("quick_ratio")
        cashr = assessments.get("cash_ratio")
        liq_items = [a for a in [cr, qr, cashr] if a is not None]

        has_liq_alert = any(a.status == AssessmentStatus.ALERT for a in liq_items)
        has_liq_watch = any(a.status == AssessmentStatus.WATCH for a in liq_items)
        all_liq_adequate = len(liq_items) > 0 and all(a.status == AssessmentStatus.ADEQUATE for a in liq_items)

        if all_liq_adequate:
            overviews["liquidity"] = "Năng lực thanh toán ngắn hạn dồi dào, các tỷ số thanh toán hiện hành, nhanh và tức thời đều vượt ngưỡng sàng lọc an toàn."
        elif has_liq_alert:
            overviews["liquidity"] = "Áp lực thanh toán ngắn hạn đáng kể, xuất hiện tỷ số thanh khoản dưới ngưỡng sàng lọc tối thiểu."
        elif has_liq_watch:
            overviews["liquidity"] = "Khả năng thanh toán nợ ngắn hạn duy trì ở mức vừa phải, nằm trong vùng đệm cần theo dõi sát."
        else:
            overviews["liquidity"] = "Số liệu thanh khoản đã được ghi nhận nhưng cần thêm thông tin lịch đến hạn nợ để kết luận toàn diện."

        # 2. Cơ cấu vốn
        dta = assessments.get("debt_to_assets")
        dte = assessments.get("debt_to_equity")
        eqr = assessments.get("equity_ratio")
        lev_items = [a for a in [dta, dte, eqr] if a is not None]

        has_lev_undefined = any(a.status == AssessmentStatus.UNDEFINED for a in lev_items)
        has_lev_alert = any(a.status == AssessmentStatus.ALERT for a in lev_items)
        has_lev_watch = any(a.status == AssessmentStatus.WATCH for a in lev_items)
        all_lev_adequate = len(lev_items) > 0 and all(a.status == AssessmentStatus.ADEQUATE for a in lev_items)

        if has_lev_undefined:
            overviews["leverage"] = "RỦI RO ĐẶC BIỆT NGHIÊM TRỌNG: Doanh nghiệp bị âm vốn chủ sở hữu, phụ thuộc 100% vào nợ phải trả."
        elif has_lev_alert:
            overviews["leverage"] = "Mức độ đòn bẩy tài chính cao, xuất hiện chỉ tiêu vượt ngưỡng an toàn (nợ chiếm trên 70% tổng tài sản hoặc D/E > 2.0 lần), tiềm ẩn áp lực trả nợ."
        elif has_lev_watch:
            overviews["leverage"] = "Đòn bẩy tài chính ở mức trung bình (nợ chiếm khoảng 50% - 70% tổng tài sản), các chỉ tiêu nợ/tài sản và nợ/vốn chủ sở hữu nằm trong vùng đệm theo dõi."
        elif all_lev_adequate:
            overviews["leverage"] = "Cơ cấu vốn an toàn, mức độ tự chủ tài chính tốt với phần lớn tài sản hình thành từ vốn tự có."
        else:
            overviews["leverage"] = "Cơ cấu vốn đã được ghi nhận nhưng cần phân tích thêm cơ cấu nợ vay chịu lãi."

        # 3. Hiệu quả hoạt động
        tat = assessments.get("total_asset_turnover")
        it = assessments.get("inventory_turnover")
        if tat and tat.value and it and it.value:
            overviews["efficiency"] = (
                f"Vòng quay tài sản đạt {tat.formatted_value} và vòng quay hàng tồn kho đạt {it.formatted_value}. "
                f"Cần đối chiếu với chu kỳ hoạt động và chuẩn ngành để đánh giá năng lực khai thác tài sản."
            )
        else:
            overviews["efficiency"] = "Hiệu quả hoạt động đã được tính toán nhưng chưa áp dụng ngưỡng tốt/xấu khi chưa có benchmark ngành."

        # 4. Khả năng sinh lời
        npm = assessments.get("net_profit_margin")
        roe = assessments.get("roe")
        if roe and roe.status == AssessmentStatus.UNDEFINED:
            overviews["profitability"] = "Chỉ số sinh lời không phản ánh bình thường do vốn chủ sở hữu âm; doanh nghiệp tích lũy lỗ kéo dài."
        elif npm and npm.status == AssessmentStatus.ALERT:
            overviews["profitability"] = "Kết quả kinh doanh thua lỗ trong kỳ, biên lợi nhuận ròng mang giá trị âm."
        elif npm and npm.value and npm.value > Decimal("0"):
            overviews["profitability"] = (
                f"Doanh nghiệp duy trì kết quả kinh doanh có lãi với tỷ suất lợi nhuận sau thuế {npm.formatted_value} "
                f"và tỷ suất sinh lời trên vốn chủ sở hữu ROE đạt {roe.formatted_value if roe else 'N/A'}."
            )
        else:
            overviews["profitability"] = "Khả năng sinh lời hòa vốn hoặc chưa đủ dữ liệu xác định."

        return overviews

    def _compile_key_findings(
        self,
        assessments: Dict[str, RatioAssessment],
        warnings: List[FinancialWarning],
        overall_status: OverallHealthStatus,
    ) -> List[str]:
        """Compile executive bullet points summarizing core analytical findings."""
        findings: List[str] = []

        # Finding on Overall Status
        if overall_status == OverallHealthStatus.INSUFFICIENT_DATA:
            findings.append("Dữ liệu báo cáo tài chính thiếu hụt đáng kể; chưa đủ cơ sở dữ liệu để đưa ra nhận định tổng thể tin cậy.")
        elif overall_status == OverallHealthStatus.NEEDS_ATTENTION:
            findings.append("Hệ thống phát hiện các tín hiệu rủi ro tài chính cần chú ý đặc biệt ở nhóm đòn bẩy hoặc thanh khoản.")
        elif overall_status == OverallHealthStatus.MIXED:
            findings.append("Sức khỏe tài chính ở mức trung bình đan xen: Doanh nghiệp có kết quả sinh lời dương nhưng các chỉ số thanh toán và đòn bẩy đang nằm trong vùng đệm cần theo dõi.")
        else:
            findings.append("Không có cảnh báo rủi ro trọng yếu nào bị kích hoạt theo bộ quy tắc sàng lọc minh họa hiện tại.")

        # Top severity warnings highlight
        top_critical_or_high = [w for w in warnings if w.severity in (WarningSeverity.CRITICAL, WarningSeverity.HIGH)]
        for w in top_critical_or_high[:2]:
            findings.append(f"Cảnh báo trọng yếu: {w.title} ({w.evidence}).")

        # Profitability summary finding
        npm = assessments.get("net_profit_margin")
        if npm and npm.value and npm.value > Decimal("0"):
            findings.append(f"Khả năng sinh lời dương trong kỳ với biên lợi nhuận sau thuế đạt {npm.formatted_value}.")
        elif npm and npm.value and npm.value < Decimal("0"):
            findings.append(f"Cảnh báo: Biên lợi nhuận sau thuế âm ({npm.formatted_value}), hoạt động kinh doanh phát sinh lỗ.")

        return findings
